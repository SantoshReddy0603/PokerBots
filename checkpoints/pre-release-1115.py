SRC_DECISIONS = frozenset({'preflop'})


def load(blob):
    return zlib.decompress(base64.b64decode(blob)).decode("utf-8")


def module(blob, name):
    space = {"__name__": name, "__builtins__": __builtins__}
    exec(compile(load(blob), "bot.py", "exec"), space)
    return space


def emit(reply):
    sys.stdout.write(json.dumps(reply, separators=(",", ":")) + "\n")
    sys.stdout.flush()


class Range:
    """Vectorised range engine: observes everything, answers when asked."""

    def __init__(self):
        self.g = module(RANGE_ENGINE, "range_engine")
        self.out = []
        self.g["send"] = self.out.append

    def see(self, msg):
        kind = msg.get("type")
        state = self.g["STATE"]
        observe = self.g["observe"]
        if kind in ("action_request", "discard_request"):
            observe(state.observe, msg)
        elif kind == "init":
            observe(state.configure, msg)
        elif kind == "new_hand":
            observe(state.new_hand, msg)
        elif kind == "discard_result":
            observe(state.discard_result, msg)
        elif kind == "hand_result":
            observe(state.hand_result, msg)

    def answer(self, msg):
        del self.out[:]
        if msg["type"] == "action_request":
            self.g["handle_action"](msg)
        else:
            self.g["handle_discard"](msg)
        return self.out[-1] if self.out else None


class Src:
    """Engine built from src/: frequency model with range-weighted equity."""

    def __init__(self):
        self.g = module(SRC_ENGINE, "src_engine")
        self.state = self.g["State"]()

    def see(self, msg):
        kind = msg.get("type")
        if kind == "action_request":
            self.state.history = msg["history"]
        elif kind != "discard_request":
            self.state.observe(msg, kind)

    def answer(self, msg):
        g, state = self.g, self.state
        if msg["type"] == "action_request":
            if state.locked:
                return g["normalize"](msg, None)
            return g["normalize"](msg, *g["choose_action"](state, msg))
        hole = tuple(g["CARD_ID"][c] for c in msg["hole_cards"])
        card = g["choose_discard"](state, msg, hole)
        if card not in hole:
            card = min(hole)
        return {"type": "discard", "card": g["CARDS"][card]}


def decision(msg):
    return "discard" if msg["type"] == "discard_request" else msg.get("street")


def play():
    engines = [Range(), Src()]
    for line in sys.stdin:
        try:
            msg = json.loads(line)
        except ValueError:
            continue
        if not isinstance(msg, dict):
            continue
        kind = msg.get("type")
        if kind == "match_end":
            return
        for engine in engines:
            try:
                engine.see(msg)
            except Exception:
                pass
        if kind not in ("action_request", "discard_request"):
            continue
        first = engines[1] if decision(msg) in SRC_DECISIONS else engines[0]
        reply = None
        for engine in (first, engines[0]):
            try:
                reply = engine.answer(msg)
            except Exception:
                reply = None
            if reply is not None:
                break
        if reply is None:
            legal = msg.get("legal_actions") or []
            if kind == "discard_request":
                reply = {"type": "discard", "card": msg["hole_cards"][0]}
            else:
                reply = {"type": "action", "action": "check" if "check" in legal else "fold"}
        engines[1].state.pending = reply
        emit(reply)


